def _write_text_pdf(path: Path) -> None:
    """Three pages: distinct markers, a hyphenated word split across lines."""
    sheet = canvas.Canvas(str(path), pagesize=letter)
    sheet.setTitle("Synthetic Datasheet Rev A")
    sheet.setAuthor("BoardModeler synthetic fixture")
    sheet.drawString(72, 700, "Page one alpha marker")
    sheet.showPage()
    sheet.drawString(72, 700, "Page two bravo marker")
    sheet.drawString(72, 680, "The word is configura-")
    sheet.drawString(72, 660, "tion split by hyphenation")
    sheet.showPage()
    sheet.drawString(72, 700, "Page three charlie marker")
    sheet.showPage()
    sheet.save()


def _write_vector_pdf(path: Path) -> None:
    """One page of pure vector art: content, but no text and no raster."""
    sheet = canvas.Canvas(str(path), pagesize=letter)
    sheet.rect(100, 100, 200, 200, stroke=1, fill=0)
    sheet.circle(300, 300, 50, stroke=1, fill=0)
    sheet.line(72, 72, 500, 700)
    sheet.showPage()
    sheet.save()


def _write_image_only_pdf(path: Path, image: Path) -> None:
    """One image page (no text) followed by one text page."""
    sheet = canvas.Canvas(str(path), pagesize=letter)
    sheet.drawImage(str(image), 72, 500, width=40, height=40)
    sheet.showPage()
    sheet.drawString(72, 700, "The only text in this file")
    sheet.showPage()
    sheet.save()


def _write_labeled_pdf(path: Path) -> None:
    """Two pages whose declared labels (i, ii) differ from their PDF indices."""
    sheet = canvas.Canvas(str(path), pagesize=letter)
    sheet.addPageLabel(0, style="ROMAN_LOWER", start=1)
    sheet.drawString(72, 700, "Cover")
    sheet.showPage()
    sheet.drawString(72, 700, "Body")
    sheet.showPage()
    sheet.save()


def _write_blank_second_page_pdf(path: Path) -> None:
    """One text page followed by a page with no content at all."""
    sheet = canvas.Canvas(str(path), pagesize=letter)
    sheet.drawString(72, 700, "Only content in the document")
    sheet.showPage()
    sheet.showPage()
    sheet.save()


def _write_large_page_pdf(path: Path, width: float, height: float) -> None:
    sheet = canvas.Canvas(str(path), pagesize=(width, height))
    sheet.drawString(10, 10, "poster")
    sheet.showPage()
    sheet.save()


def _write_red_page_pdf(path: Path) -> None:
    sheet = canvas.Canvas(str(path), pagesize=letter)
    sheet.setFillColorRGB(1, 0, 0)
    sheet.rect(0, 0, 612, 792, stroke=0, fill=1)
    sheet.showPage()
    sheet.save()


def _png_header_and_first_pixel(data: bytes) -> tuple[int, int, tuple[int, int, int]]:
    """Decode an 8-bit RGB PNG far enough to read its size and first pixel."""
    assert data[:8] == b"\x89PNG\r\n\x1a\n", "not a PNG"
    offset = 8
    header = b""
    idat = b""
    while offset < len(data):
        length = int.from_bytes(data[offset : offset + 4], "big")
        tag = data[offset + 4 : offset + 8]
        payload = data[offset + 8 : offset + 8 + length]
        if tag == b"IHDR":
            header = payload
        elif tag == b"IDAT":
            idat += payload
        offset += 12 + length
    width, height, depth, color_type = struct.unpack(">IIBB", header[:10])
    assert depth == 8 and color_type == 2, f"unexpected depth/colour type: {depth}/{color_type}"
    scanlines = zlib.decompress(idat)
    assert scanlines[0] == 0, "first scanline is expected to be unfiltered"
    return width, height, tuple(scanlines[1:4])


