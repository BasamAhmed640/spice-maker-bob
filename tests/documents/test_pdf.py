def test_reads_page_count_title_and_hash(tmp_path: Path) -> None:
    source = tmp_path / "synthetic_datasheet.pdf"
    _write_text_pdf(source)

    document = read_pdf(source)

    assert document.page_count == 3
    assert len(document.pages) == 3
    assert [page.pdf_page for page in document.pages] == [0, 1, 2]
    assert document.title == "Synthetic Datasheet Rev A"
    assert document.metadata["Author"] == "BoardModeler synthetic fixture"
    assert document.text_extraction == "embedded"


def test_file_hash_is_the_hash_of_the_bytes(tmp_path: Path) -> None:
    source = tmp_path / "synthetic_datasheet.pdf"
    _write_text_pdf(source)

    document = read_pdf(source)

    assert document.file_hash == hashlib.sha256(source.read_bytes()).hexdigest()


def test_page_text_is_scoped_to_its_own_page(tmp_path: Path) -> None:
    source = tmp_path / "synthetic_datasheet.pdf"
    _write_text_pdf(source)

    document = read_pdf(source)

    assert "bravo marker" in page_text(document, 1)
    assert "bravo marker" not in page_text(document, 0)
    assert "alpha marker" in page_text(document, 0)
    assert document.pages[1].char_count == len(page_text(document, 1))
    assert document.pages[1].has_embedded_text is True


def test_page_text_rejects_an_out_of_range_page(tmp_path: Path) -> None:
    source = tmp_path / "synthetic_datasheet.pdf"
    _write_text_pdf(source)
    document = read_pdf(source)

    with pytest.raises(IndexError):
        page_text(document, 3)
    with pytest.raises(IndexError):
        page_text(document, -1)


def test_max_pages_limits_the_read_pages_but_not_the_page_count(tmp_path: Path) -> None:
    source = tmp_path / "synthetic_datasheet.pdf"
    _write_text_pdf(source)

    document = read_pdf(source, max_pages=2)

    assert document.page_count == 3
    assert [page.pdf_page for page in document.pages] == [0, 1]
    with pytest.raises(IndexError):
        page_text(document, 2)


def test_max_pages_must_be_positive(tmp_path: Path) -> None:
    source = tmp_path / "synthetic_datasheet.pdf"
