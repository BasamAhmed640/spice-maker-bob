def test_excerpt_is_found_on_a_page_and_rejected_on_another(tmp_path: Path) -> None:
    source = tmp_path / "synthetic_datasheet.pdf"
    _write_text_pdf(source)
    document = read_pdf(source)

    assert excerpt_on_page(document, "Page two bravo marker", 1) is True
    assert excerpt_on_page(document, "Page two bravo marker", 0) is False
    assert excerpt_on_page(document, "Page three charlie marker", 2) is True


def test_excerpt_survives_line_break_and_hyphenation(tmp_path: Path) -> None:
    source = tmp_path / "synthetic_datasheet.pdf"
    _write_text_pdf(source)
    document = read_pdf(source)

    # The page really contains "configura-\ntion"; the citation is the word.
    assert "configura-" in page_text(document, 1)
    assert "configuration" not in page_text(document, 1)
    assert excerpt_on_page(document, "configuration split by hyphenation", 1) is True
    # The reverse direction: the citation keeps the printed break.
    assert excerpt_on_page(document, "The word is configura-\ntion", 1) is True
    # A citation broken across a line without hyphenation still matches.
    assert excerpt_on_page(document, "bravo marker The word", 1) is True


def test_invented_excerpt_is_rejected(tmp_path: Path) -> None:
    source = tmp_path / "synthetic_datasheet.pdf"
    _write_text_pdf(source)
    document = read_pdf(source)

    invented = "The device survives a 42 V transient for 10 ms"
    for page in range(document.page_count):
        assert excerpt_on_page(document, invented, page) is False
    assert excerpt_on_page(document, "", 1) is False
    assert excerpt_on_page(document, "   \n\t ", 1) is False


def test_excerpt_compares_only_the_first_max_chars(tmp_path: Path) -> None:
    source = tmp_path / "synthetic_datasheet.pdf"
    _write_text_pdf(source)
    document = read_pdf(source)

    # The page contains the marker but none of the fabricated tail, so the full
    # excerpt must be rejected and only the first 21 characters may be compared.
    excerpt = "Page two bravo marker " + "x" * 400
    assert excerpt_on_page(document, excerpt, 1) is False
    assert excerpt_on_page(document, excerpt, 1, max_chars=21) is True
    invented_prefix = "y" * 400 + " Page two bravo marker"
    assert excerpt_on_page(document, invented_prefix, 1) is False
    with pytest.raises(ValueError):
        excerpt_on_page(document, "Page two bravo marker", 1, max_chars=0)


def test_normalize_for_citation_collapses_whitespace_and_typography() -> None:
    collapsed = normalize_for_citation("  Output\tvoltage\n\n rises   slowly ")
    assert collapsed == "Output voltage rises slowly"

    assert normalize_for_citation("3\u20135 V \u2013 5\u22126 V") == "3-5 V - 5-6 V"
    assert normalize_for_citation("\u201cconfiguration\u201d") == '"configuration"'
    assert normalize_for_citation("don\u2019t") == "don't"
    assert normalize_for_citation("con\ufb01guration \ufb02ow") == "configuration flow"
    assert normalize_for_citation("soft\u00adhyphen") == "softhyphen"
    assert normalize_for_citation("\u00a0") == ""


