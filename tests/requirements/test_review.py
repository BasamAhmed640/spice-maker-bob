def test_disjoint_limits_conflict_and_are_preserved(pdf: Path) -> None:
    high = make_requirement(
        req_id="REQ_MAX_3366",
        limits={"max": 3.366, "unit": "V"},
        expression={"op": "le", "signal": "V(VOUT)", "value": 3.366, "unit": "V"},
        signal_refs=["V(VOUT)"],
    )
    low = make_requirement(
        req_id="REQ_MIN_3500",
        limits={"min": 3.5, "unit": "V"},
        expression={"op": "ge", "signal": "V(VOUT)", "value": 3.5, "unit": "V"},
        signal_refs=["V(VOUT)"],
    )
    documents = {DOC_ID: make_document(str(pdf))}

    pairs = find_conflicts([high, low])

    assert len(pairs) == 1
    first, second, reason = pairs[0]
    assert (first, second) == ("REQ_MAX_3366", "REQ_MIN_3500")
    assert "3.366" in reason and "3.5" in reason

    outcome = review([high, low], documents)

    assert outcome.conflicts == ["REQ_MAX_3366", "REQ_MIN_3500"]
    assert [item.kind for item in outcome.items] == ["conflict"]
    assert outcome.items[0].blocking is True
    assert outcome.items[0].id == "RV_conflict_REQ_MAX_3366__REQ_MIN_3500"
    assert outcome.items[0].affected_requirement_ids == ["REQ_MAX_3366", "REQ_MIN_3500"]

    applied = {
        requirement.req_id: requirement for requirement in apply_review([high, low], outcome)
    }

    assert applied["REQ_MAX_3366"].status == "conflict"
    assert applied["REQ_MIN_3500"].status == "conflict"
    assert applied["REQ_MAX_3366"].conflicts == [f"REQ_MIN_3500: {reason}"]
    assert applied["REQ_MIN_3500"].conflicts == [f"REQ_MAX_3366: {reason}"]


