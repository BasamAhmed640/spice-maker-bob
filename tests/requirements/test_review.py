def test_citation_found_on_the_cited_page_verifies(pdf: Path) -> None:
    requirement = make_requirement()
    documents = {DOC_ID: make_document(str(pdf))}

    assert verify_citations([requirement], documents) == {requirement.req_id: True}

    outcome = review([requirement], documents)

    assert outcome.verified == [requirement.req_id]
    assert outcome.unverified == []
    assert outcome.coverage == 1.0
    assert outcome.items == []
    assert outcome.issues == []


