def test_excerpt_lookup_is_used_instead_of_the_document_file() -> None:
    requirement = make_requirement()
    documents = {DOC_ID: make_document("")}  # no file on disk: the lookup must be enough
    pages = {(DOC_ID, 0): PAGE_ONE_TEXT}

    def lookup(doc_id: str, page: int) -> str | None:
        return pages.get((doc_id, page))

    def missing(doc_id: str, page: int) -> str | None:
        return None

    assert verify_citations([requirement], documents, excerpt_lookup=lookup) == {
        requirement.req_id: True
    }
    assert verify_citations([requirement], documents, excerpt_lookup=missing) == {
        requirement.req_id: False
    }


def test_excerpt_lookup_and_the_pdf_path_agree(pdf: Path) -> None:
    requirement = make_requirement()
    documents = {DOC_ID: make_document(str(pdf))}
    parsed: PdfDocument = read_pdf(pdf)

    def lookup(doc_id: str, page: int) -> str | None:
        return page_text(parsed, page)

    assert verify_citations([requirement], documents) == verify_citations(
        [requirement], documents, excerpt_lookup=lookup
    )


def test_the_pdf_is_read_once_per_call(pdf: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    reads: list[tuple[str, int | None]] = []
    real_read_pdf = review_module.read_pdf

    def counting_read_pdf(path: str | Path, *, max_pages: int | None = None) -> PdfDocument:
        reads.append((str(path), max_pages))
        return real_read_pdf(path, max_pages=max_pages)

    monkeypatch.setattr(review_module, "read_pdf", counting_read_pdf)
    requirements = [make_requirement(req_id="REQ_A"), make_requirement(req_id="REQ_B", page=1)]
    documents = {DOC_ID: make_document(str(pdf))}

    outcome = review(requirements, documents)

    assert outcome.verified == ["REQ_A"]
    assert outcome.unverified == ["REQ_B"]
    # One read, and only the pages that are cited.
    assert reads == [(str(pdf), 2)]


