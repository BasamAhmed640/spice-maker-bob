def test_apply_review_sets_citation_verified_and_keeps_the_expression(pdf: Path) -> None:
    verified = make_requirement(
        req_id="REQ_GOOD",
        expression={"op": "le", "signal": "V(VOUT)", "value": 0.802, "unit": "V"},
        signal_refs=["V(VOUT)"],
    )
    unverified = make_requirement(
        req_id="REQ_BAD",
        page=1,
        citation_verified=True,  # a stale claim the review has to overwrite
        expression={"op": "ge", "signal": "V(FB)", "value": 0.788, "unit": "V"},
        signal_refs=["V(FB)"],
    )
    fixture = make_requirement(
        req_id="REQ_FIXTURE", origin=RequirementOrigin.TEST_FIXTURE, page=None
    )
    documents = {DOC_ID: make_document(str(pdf))}

    outcome = review([verified, unverified, fixture], documents)
    applied = {
        requirement.req_id: requirement
        for requirement in apply_review([verified, unverified, fixture], outcome)
    }

    assert applied["REQ_GOOD"].citation_verified is True
    assert applied["REQ_BAD"].citation_verified is False
    assert applied["REQ_BAD"].expression is not None
    assert applied["REQ_FIXTURE"].citation_verified is False
    assert applied["REQ_FIXTURE"].status == "active"


def test_apply_review_is_idempotent(pdf: Path) -> None:
    high = make_requirement(req_id="REQ_HIGH", limits={"max": 3.366, "unit": "V"})
    low = make_requirement(req_id="REQ_LOW", limits={"min": 3.5, "unit": "V"})
    documents = {DOC_ID: make_document(str(pdf))}

    outcome = review([high, low], documents)
    once = apply_review([high, low], outcome)
    twice = apply_review(once, outcome)

    assert [requirement.model_dump() for requirement in once] == [
        requirement.model_dump() for requirement in twice
    ]


