def test_review_is_deterministic(pdf: Path) -> None:
    requirements = [
        make_requirement(req_id="REQ_GOOD"),
        make_requirement(req_id="REQ_BAD", page=1),
        make_requirement(req_id="REQ_HIGH", limits={"max": 3.366, "unit": "V"}),
        make_requirement(req_id="REQ_LOW", limits={"min": 3.5, "unit": "V"}),
        make_requirement(
            req_id="REQ_AMBIGUOUS", excerpt="Reference voltage is 0.795 V, TA = 25 C."
        ),
    ]
    documents = {DOC_ID: make_document(str(pdf))}

    first = review(requirements, documents)
    second = review(requirements, documents)

    assert first.verified == second.verified
    assert first.unverified == second.unverified
    assert first.conflicts == second.conflicts
    assert first.issues == second.issues
    assert [item.model_dump() for item in first.items] == [
        item.model_dump() for item in second.items
    ]
    assert len(first.items) >= 4
    assert {item.kind for item in first.items} == {"missing_evidence", "conflict", "ambiguity"}


