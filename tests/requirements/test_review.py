DOC_ID = "DOC_synthetic_review"
SECOND_DOC_ID = "DOC_synthetic_review_rev_b"
PAGE_ONE_TEXT = "Reference voltage is 0.795 V typical."
PAGE_TWO_TEXT = "Page two carries only this sentence."
EXCERPT_ON_PAGE_ONE = "Reference voltage is 0.795 V"
INVENTED_EXCERPT = "This sentence was never printed anywhere."
DEFAULT_LIMITS = {"min": 0.788, "typ": 0.795, "max": 0.802, "unit": "V"}


def _write_two_page_pdf(path: Path) -> None:
    """Two synthetic pages with distinct, made-up markers."""
    sheet = canvas.Canvas(str(path), pagesize=letter)
    sheet.setTitle("Synthetic review datasheet")
    sheet.drawString(72, 700, PAGE_ONE_TEXT)
    sheet.showPage()
    sheet.drawString(72, 700, PAGE_TWO_TEXT)
    sheet.showPage()
    sheet.save()


@pytest.fixture
def pdf(tmp_path: Path) -> Path:
    path = tmp_path / "synthetic_review.pdf"
    _write_two_page_pdf(path)
    return path


def make_document(
    path: str,
    *,
    doc_id: str = DOC_ID,
    page_count: int = 2,
    text_extraction: str = "embedded",
) -> DocumentRecord:
    return DocumentRecord(
        doc_id=doc_id,
        title="Synthetic review datasheet",
        doc_type="datasheet",
        provenance="synthetic_fixture",
        file_hash="1" * 64,
        page_count=page_count,
        text_extraction=text_extraction,
        path=path,
    )


def make_requirement(
    req_id: str = "REQ_SYNTH_ELEC_001",
    *,
    origin: RequirementOrigin = RequirementOrigin.DOCUMENT,
    criticality: Criticality = Criticality.CRITICAL,
    statement: str = "The 3V3 output stays within its regulation limits.",
    excerpt: str = EXCERPT_ON_PAGE_ONE,
    section: str | None = "Electrical Characteristics",
    doc_id: str = DOC_ID,
    page: int | None = 0,
    limits: dict[str, Any] | None = DEFAULT_LIMITS,
    expression: dict[str, Any] | None = None,
    conditions: list[dict[str, Any]] | None = None,
    signal_refs: list[str] | None = None,
    applies_to: str = "U1",
    configuration: str | None = None,
    citation_verified: bool = False,
    status: str = "active",
) -> Requirement:
    evidence = []
    if page is not None or origin is RequirementOrigin.DOCUMENT:
        evidence = [
            EvidenceRef(
                doc_id=doc_id,
                page=None if page is None else PageRef(pdf_page=page),
                section=section,
                excerpt=excerpt,
                extraction=EvidenceExtraction.SYNTHETIC_FIXTURE
                if origin is RequirementOrigin.TEST_FIXTURE
                else EvidenceExtraction.EMBEDDED_TEXT,
            )
        ]
    return Requirement(
        req_id=req_id,
        applies_to=applies_to,
        configuration=configuration,
        kind=RequirementKind.ELECTRICAL,
        **{
            "class": RequirementClass.DOCUMENTED_LIMIT,
            "criticality": criticality,
            "origin": origin,
            "statement": statement,
            "limits": limit(limits),
            "expression": expression,
            "conditions": [Condition(**condition) for condition in conditions or []],
            "signal_refs": signal_refs or [],
            "evidence": evidence,
            "citation_verified": citation_verified,
            "status": status,
        },
    )


def limit(values: dict[str, Any] | None) -> Limit | None:
    return None if values is None else Limit(**values)


